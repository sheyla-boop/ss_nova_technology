    <p class="eyebrow">Seguridad de la cuenta</p>
    <h1>Política de contraseñas</h1>
    <p>Para crear una cuenta o establecer una contraseña nueva desde administración, la contraseña debe cumplir estos requisitos:</p>
    <ul>
        <li>Tener al menos 8 caracteres y al menos un signo o símbolo.</li>
        <li>Ser única para SS Nova Technology; no reutilices contraseñas de otros servicios.</li>
        <li>No incluir datos fáciles de adivinar, como tu nombre, correo, fecha de nacimiento o secuencias comunes.</li>
    </ul>
    <p>Se recomienda usar una frase larga y difícil de predecir o un administrador de contraseñas. No compartas tu contraseña y cámbiala de inmediato si sospechas que alguien la conoce.</p>
    <p>Las contraseñas se almacenan con hash, no en texto legible. Si olvidas la tuya, contacta al administrador del sitio; nunca envíes tu contraseña por correo.</p>
    <p class="form-note">El mínimo se aplica al crear o cambiar una contraseña. Las cuentas existentes pueden continuar usando la contraseña que ya tenían.</p>
